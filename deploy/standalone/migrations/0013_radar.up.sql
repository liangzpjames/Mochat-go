  `employee_card` tinyint(1) DEFAULT '0' COMMENT '成员名片（0：不显示，1：显示）',
  `action_notice` tinyint(1) DEFAULT '0' COMMENT '行为通知（0：不通知，1：通知）',
  `dynamic_notice` tinyint(1) DEFAULT '0' COMMENT '动态通知（0：不通知，1：通知）',
  `contact_tags` json DEFAULT NULL COMMENT '客户标签',
  `tag_status` tinyint(1) DEFAULT NULL COMMENT '客户标签（0：否，1：是）',
  `contact_grade` json DEFAULT NULL COMMENT '客户评分',
